/** 빌드 시점의 오늘 날짜 (YYYY-MM-DD, UTC 기준) */
export function today(): string {
  return new Date().toISOString().slice(0, 10);
}

/** publishAt 이 없거나 오늘 이전이면 공개 상태 */
export function isGuideLive(g: Guide, now = today()): boolean {
  return !g.publishAt || g.publishAt <= now;
}

/** 현재 공개된 글만 (예약 발행 대기 글 제외) */
export function getLiveGuides(now = today()): Guide[] {
  return GUIDES.filter((g) => isGuideLive(g, now));
}

export function getGuide(slug: string): Guide | undefined {
  return GUIDES.find((g) => g.slug === slug);
}
